function rellenarSelectoresC3(escenarios) {
    const indice = document.getElementById('indiceC3');
    const escenario = document.getElementById('escenarioC3');

    indice.replaceChildren(new Option('Selecciona un índice', ''));
    for (const nombre of Object.keys(escenarios)) {
        indice.appendChild(new Option(nombre, nombre));
    }

    escenario.replaceChildren(new Option('Selecciona un escenario', ''));
    for (const [valor, etiqueta] of Object.entries(ETIQUETAS_ESCENARIO_C3)) {
        escenario.appendChild(new Option(etiqueta, valor));
    }

    indice.disabled = false;
    escenario.disabled = false;
    indice.addEventListener('change', () => actualizarRentabilidadC3(escenarios));
    escenario.addEventListener('change', () => actualizarRentabilidadC3(escenarios));
}

function actualizarRentabilidadC3(escenarios) {
    const indice = document.getElementById('indiceC3').value;
    const escenario = document.getElementById('escenarioC3').value;
    const tasas = escenarios[indice]?.[escenario];
    if (tasas) document.getElementById('rentabC3').value = tasas;
}

window.addEventListener('DOMContentLoaded', () => rellenarSelectoresC3(ESCENARIOS_C3));